package pz

import (
	"reflect"
	"testing"
)

func TestTOCPages(t *testing.T) {
	toc := []tocEntry{{1, "1. Общие сведения"}, {2, "1.1. Назначение"}, {1, "2. Описание логической структуры"},
		{2, "2.1. Структура программы с описанием функций составных частей и связи между ними"}, {1, "ПРИЛОЖЕНИЕ А. Листинги программ"}}
	pages := []string{
		"титул",
		"          СОДЕРЖАНИЕ\n1. Общие сведения\n1.1. Назначение\n2. Описание логической структуры",
		"            1. ОБЩИЕ СВЕДЕНИЯ\nтекст про назначение\n   1.1. Назначение\n",
		"текст",
		"   2. ОПИСАНИЕ ЛОГИЧЕСКОЙ СТРУКТУРЫ\n  2.1. Структура программы с описанием функций составных\nчастей и связи между ними",
		"          ПРИЛОЖЕНИЕ А\n        Листинги программ",
	}
	got, err := tocPages(toc, pages)
	if err != nil {
		t.Fatal(err)
	}
	if want := []int{3, 3, 5, 5, 6}; !reflect.DeepEqual(got, want) {
		t.Errorf("страницы %v, ждём %v", got, want)
	}
	if _, err := tocPages(append(toc, tocEntry{1, "Нет такого"}), pages); err == nil {
		t.Error("ненайденный заголовок должен давать ошибку")
	}
}
